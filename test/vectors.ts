// Writes native/fixtures/crypto-vectors.json: deterministic seal() outputs from tweetnacl-js that the
// native apps must reproduce byte for byte (plans/native-apps.md D6). `npm run vectors`; the crypto test
// checks the committed file still matches.

import { writeFileSync } from "node:fs";
import { b64u, sealWithNonce } from "../src/crypto.ts";

const bytes = (n: number, f: (i: number) => number) => Uint8Array.from({ length: n }, (_, i) => f(i) & 0xff);

export function vectors() {
	const key = bytes(32, (i) => i + 1);
	const nonce = bytes(24, (i) => 0xa0 + i);
	const wrongKey = bytes(32, (i) => 0xff - i);
	const values: [string, unknown][] = [
		["ascii", { t: 1760000000000, m: "hub", p: {} }],
		["unicode", { text: "wörld 👋 日本語", n: -1.5, ok: true, none: null }],
		["array", [1, "two", { three: [3] }]],
		["string", "plain"],
		["large", { text: "x".repeat(100 * 1024) }],
	];
	const valid = values.map(([name, value]) => ({ name, value, json: JSON.stringify(value), sealed: sealWithNonce(key, nonce, value) }));
	const good = Buffer.from(valid[0].sealed, "base64url");
	const tampered = Buffer.from(good);
	tampered[tampered.length - 1] ^= 1;
	const invalid = [
		{ name: "tampered", key: b64u(key), sealed: tampered.toString("base64url") },
		{ name: "short", key: b64u(key), sealed: good.subarray(0, 24 + 15).toString("base64url") },
		{ name: "wrong key", key: b64u(wrongKey), sealed: valid[0].sealed },
	];
	return { about: "Generated by test/vectors.ts (npm run vectors). base64url(nonce24 || secretbox(JSON(value))).", key: b64u(key), nonce: b64u(nonce), valid, invalid };
}

export const VECTORS_PATH = new URL("../native/fixtures/crypto-vectors.json", import.meta.url);
export const render = () => `${JSON.stringify(vectors(), null, 1)}\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
	writeFileSync(VECTORS_PATH, render());
	console.log(`wrote ${VECTORS_PATH.pathname}`);
}
